// כל הטקסטים לקול
export function moreClips() {
  const out = [];
  for (const T of [NUM_UI, MATH_UI, STORY_UI, SONG_UI, EN_UI]) for (const [k, t] of Object.entries(T)) out.push([`ui/${k}`, t, 'he']);
  NUMW.forEach((w, n) => out.push([`N/${n}`, w, 'word']));
  STORIES.forEach((s) => {
    out.push([`S/${s.id}/title`, s.title, 'he']);
    s.pages.forEach((p, i) => out.push([`S/${s.id}/p${i}`, p, 'story']));
    s.questions.forEach((q, i) => out.push([`S/${s.id}/q${i}`, q.q, 'he']));
    out.push([`S/${s.id}/talk`, s.talk, 'he']);
  });
  RHYME_WORDS.forEach((r) => out.push([`R/${r.id}`, r.w, 'word']));
  SYL_WORDS.forEach((r) => out.push([`R/${r.id}`, r.w, 'word']));
  SONGS.forEach((s) => { s.lines.forEach((l, i) => out.push([`G/${s.id}/${i}`, l, 'song'])); out.push([`G/${s.id}/q`, s.q, 'he']); });
  // אנגלית: כל מילה באנגלית (יוגי) והסבר בעברית (לולה)
  const seen = new Set();
  EN_THEMES.forEach((t) => t.sets.forEach((s) => s.words.forEach((w) => {
    const k = enKey(w.en);
    if (seen.has(k)) return; seen.add(k);
    out.push([`E/w/${k}`, w.en, 'en-word']);
    out.push([`ui/en_gloss_${k}`, trf('{0}, בְּאַנְגְּלִית זֶה:', w.he), 'he']);
  })));
  // קטע נוסף לצד הערבי (P is for Pizza), נוצר תמיד כי קטעי האנגלית משותפים
  out.push(['E/abc/p_pizza', 'P. P is for Pizza.', 'en-line']);
  ABC.forEach((a) => {
    out.push([`E/abc/${a.k}`, a.L === 'X' ? 'X. X is in fox.' : `${a.L}. ${a.L} is for ${a.w}.`, 'en-line']);
    out.push([`E/abcn/${a.L.toLowerCase()}`, a.L, 'en-letter']);

    const k = enKey(a.w);
    if (!seen.has(k)) { seen.add(k); out.push([`E/w/${k}`, a.w, 'en-word']); }
  });
  return out;
}

