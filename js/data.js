// משפטים לכל אות. נבנים כאן כדי שגם המשחק וגם מחולל השמע ישתמשו באותו טקסט בדיוק.
export function letterLines(l) {
  const region = REGIONS.find((r) => r.id === l.region);
  const where = l.final ? 'נִגְמֶרֶת' : 'מַתְחִילָה';
  return {
    name: l.name,
    friend1: `שָׁלוֹם, לוּלָה! אֲנִי ${l.friend.name}.`,
    friend2: `מָצָאתִי אוֹת קְטַנָּה שֶׁהִתְחַבְּאָה אֶצְלִי ${region.place}. זוֹ הָאוֹת ${l.name}!`,
    intro: `זוֹ הָאוֹת ${l.name}. ${l.hint}`,
    syl: l.syl.join('... ') + '.',
    yesno: `הַאִם הַמִּלָּה ${where} בָּאוֹת ${l.name}?`,
    done: `הַצְלָחָה גְּדוֹלָה! הָאוֹת ${l.name} חָזְרָה לַתִּיק שֶׁל לוּלָה!`,
  };
}

export function wordSentence(l, w) {
  const where = l.final ? 'נִגְמֶרֶת' : 'מַתְחִילָה';
  return `${w}. הַמִּלָּה ${w} ${where} בָּאוֹת ${l.name}.`;
}

export function regionLine(r) {
  return r.arrive;
}

export const parseWord = (s) => {
  const [w, e] = s.split('|');
  return { w, e, plain: w.replace(/[֑-ׇ]/g, '') };
};

