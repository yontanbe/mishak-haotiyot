// כל הטקסטים לקול: [מזהה, טקסט, סוג]
export function worldClips() {
  const out = [];
  for (const W of [SIZE, WHERE, ENGLISH, ANIMALS]) for (const [k, t] of Object.entries(W.ui)) out.push([`ui/${k}`, t, 'he']);
  // משפטי דמויות
  out.push(['W/size/pnina', SIZE.ui.szPnina, 'pnina'], ['W/size/ofri', SIZE.ui.szOfri, 'ofri'], ['W/where/cat', WHERE.ui.whCat, 'cat']);
  for (const [k, t] of Object.entries(ENGLISH.en)) out.push([`E/${k}`, t, 'en-line']);
  ENGLISH.sets.forEach((s) => s.words.forEach((w) => out.push([`E/w/${w.en.toLowerCase()}`, w.en, 'en-word'])));
  ALL_ANIMALS.forEach((a) => {
    out.push([`A/${a.id}/name`, a.w, 'word']);
    if (a.s) out.push([`A/${a.id}/sound`, a.s, 'sound']);
  });
  out.push(['A/song/chorus', ANIMALS.chorus, 'song']);
  ANIMALS.habitats.forEach((h) => out.push([`A/song/${h.id}`, h.song, 'song']));
  return out;
}
