// ו' החיבור: אחרי ו' הדגש הקל נופל (וְכָחֹל ולא וְכָּחֹל)
const vav = (w) => 'וְ' + w.replace(/^([בגדכפת][\u05B0-\u05BB]*)\u05BC/, '$1');

// משפטים לכל צבע
export function colorLines(c) {
  const lines = {
    name: c.m,
    friend1: `שָׁלוֹם, לוּלָה! אֲנִי טִפָּה ${c.f}!`,
    friend2: `עֲנַן הָאָפֹר לָקַח אֶת הַצֶּבַע שֶׁלִּי. תַּעַזְרוּ לִי לְהַחֲזִיר אֶת הַצֶּבַע ${c.def}?`,
    intro: `זֶה הַצֶּבַע ${c.m}. ${c.m}!`,
    where: `אֵיפֹה הַצֶּבַע ${c.def}?`,
    which: `אֵיזֶה מֵהֶם ${c.m}?`,
    pick: `גְּעוּ בְּכָל הַדְּבָרִים ${c.defpl}.`,
    bubbles: `פּוֹצְצוּ רַק בּוּעוֹת ${c.fpl}!`,
    done: `הַצְלָחָה! הַצֶּבַע ${c.def} חָזַר לָעוֹלָם!`,
  };
  if (c.mix) {
    const [a, b] = c.mix.map((id) => COLOR_BY_ID[id]);
    lines.mixQ = `מָה יִקְרֶה אִם נְעַרְבֵּב ${a.m} ${vav(b.m)}?`;
    lines.mixA = `${a.m} ${vav(b.m)} בְּיַחַד עוֹשִׂים ${c.m}!`;
  }
  return lines;
}

